#!/usr/bin/env bash
set -euo pipefail

LAYOUTS=("dwindle" "master" "scrolling" "monocle")
declare -A LAYOUT_ICONS=(
  ["dwindle"]="󰕴"
  ["master"]="󱂩"
  ["scrolling"]="󰮳"
  ["monocle"]="󰁌"
)
declare -A LAYOUT_LABELS=(
  ["dwindle"]="Dwindle"
  ["master"]="Master"
  ["scrolling"]="Scrolling"
  ["monocle"]="Monocle"
)

STATE_FILE="${HYPR_STATE_HOME:-${XDG_STATE_HOME:-$HOME/.local/state}/hypr}/window-layout.lua"

show_help() {
  cat <<'HELP'
Usage: window-layout.sh [--toggle|--toggle-reverse|--set <name>|--floating|--list|--bar|--help]

  --toggle           Cycle to the next layout
  --toggle-reverse   Cycle to the previous layout
  --set <name>       Apply a specific layout
  --floating         Use Altscape's floating layouts in Windows
  --list             List layouts as name, icon and label
  --bar              Emit JSON for the bar module
HELP
}

current_layout() {
  hyprctl getoption general:layout -j 2>/dev/null \
    | sed -n 's/.*"str":[[:space:]]*"\([^"]*\)".*/\1/p'
}

apply_layout() {
  local name="$1" workflow layout_lock_fd result
  source "${HYPR_LIB_DIR:-$HOME/.local/lib/hypr}/runtime/init.bash" || return 1
  hypr_runtime_require state || return 1
  if [[ "${HYPR_WORKFLOW_TRANSITION:-0}" != 1 ]]; then
    exec {layout_lock_fd}>"$(hypr_lock_path_ensure_parent workflow)"
    flock "${layout_lock_fd}"
    trap "flock -u ${layout_lock_fd}" EXIT
  fi
  workflow="$(state_get HYPR_WORKFLOW default)"
  [[ "${name}" != floating || "${workflow}" == windows ]] || return 1
  [[ "${workflow}" == windows || "${workflow}" == macos || -z "$(state_get WORKFLOW_WINDOW_LAYOUT)" ]] || return 1
  if [[ "${name}" != floating ]]; then
    mkdir -p "${STATE_FILE%/*}"
    cat >"${STATE_FILE}" <<LUA
-- Generated by window-layout.sh. Do not edit manually.
hl.config({general = {layout = "${name}"}})
LUA
  fi
  if [[ "${HYPR_WORKFLOW_TRANSITION:-0}" != 1 && ( "${workflow}" == windows || "${workflow}" == macos ) ]]; then
    state_set WORKFLOW_LAYOUT_OVERRIDE "${name}" staterc || return 1
    if [[ "${name}" != floating ]]; then state_set WORKFLOW_LAYOUT_CHANGED 1 staterc || return 1; fi
    source "${HYPR_LIB_DIR}/window/lib/visual-presets.bash"
    source "${HYPR_LIB_DIR}/util/workflows/catalog.bash"
    workflow_load_active
    workflow_write_config || return 1
  fi
  hyprctl reload config-only -q || return 1
  if [[ "${workflow}" == windows && "${name}" != floating ]]; then
    result="$(hyprctl repl 'require("floating_windows").restore({}, false)')" || return 1
    [[ "${result}" == ok ]] || { printf '%s\n' "${result}" >&2; return 1; }
  fi
}

step_layout() {
  local current="$1" step="$2" count=${#LAYOUTS[@]} i
  for i in "${!LAYOUTS[@]}"; do
    if [[ "${LAYOUTS[$i]}" == "${current}" ]]; then
      printf '%s\n' "${LAYOUTS[$(((i + step + count) % count))]}"
      return
    fi
  done
  printf '%s\n' "${LAYOUTS[0]}"
}

handle_toggle() {
  local name=""
  name="$(step_layout "$(current_layout)" "$1")"
  apply_layout "${name}" && printf '%s\n' "${name}"
}

handle_set() {
  [[ -v LAYOUT_ICONS[$1] ]] || { printf 'unknown layout: %s\n' "$1" >&2; exit 1; }
  apply_layout "$1"
}

handle_bar() {
  local name icon label
  name="$(current_layout)"
  [[ -v LAYOUT_ICONS[$name] ]] || name="${LAYOUTS[0]}"
  icon="${LAYOUT_ICONS[$name]}"
  label="${LAYOUT_LABELS[$name]}"
  printf '{"text": "%s", "tooltip": "Layout: %s %s", "class": "custom-window-layout"}\n' \
    "${icon}" "${icon}" "${label}"
}

handle_list() {
  local name
  for name in "${LAYOUTS[@]}"; do printf '%s\t%s\t%s\n' "${name}" "${LAYOUT_ICONS[$name]}" "${LAYOUT_LABELS[$name]}"; done
}

case "${1:-}" in
  --toggle) handle_toggle 1 ;;
  --toggle-reverse) handle_toggle -1 ;;
  --floating) apply_layout floating ;;
  --set)
    shift
    [[ $# -gt 0 ]] || { printf 'Error: --set requires a layout name\n' >&2; exit 1; }
    handle_set "$1"
    ;;
  --bar) handle_bar ;;
  --list) handle_list ;;
  -h | --help | "") show_help ;;
  *) printf 'Unknown option: %s\n' "$1" >&2; show_help >&2; exit 1 ;;
esac
