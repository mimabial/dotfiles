from __future__ import annotations

import contextlib
import os

from . import CONFIG_HOME, hypr, workspaces
from .profiles import Output, Profile

HEADER = "-- Generated by hyprmoncfg"
CONF_HEADER = "# Generated by hyprmoncfg"
TARGET = os.path.expanduser(
    os.environ.get("HYPRMONCFG_MONITORS_CONF", os.path.join(CONFIG_HOME, "hypr/hyprmoncfg-monitors.lua"))
)
HYPRLAND_FIELD_NAMES = {"sdr_brightness": "sdrbrightness", "sdr_saturation": "sdrsaturation"}
OPTIONAL_FIELD_UNSET_VALUES = {
    "bitdepth": 8,
    "cm": "srgb",
    "sdr_brightness": 1,
    "sdr_saturation": 1,
    "sdr_min_luminance": None,
    "sdr_max_luminance": None,
    "min_luminance": 0,
    "max_luminance": 0,
    "max_avg_luminance": 0,
    "supports_wide_color": 0,
    "supports_hdr": 0,
    "sdr_eotf": "default",
    "icc": "",
}


def _selector(output: Output) -> str:
    """Match on description so a display survives being moved to another port."""
    description = (output.get("description") or "").strip()
    return f"desc:{description}" if description else output.get("name", "")


def _lua_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return hypr.lua_string(str(value))


def _fields(output: Output, outputs: list[Output]) -> list[tuple[str, object]]:
    if not output.get("enabled", True):
        return [("output", _selector(output)), ("disabled", True)]

    mode = str(output.get("mode", ""))
    fields: list[tuple[str, object]] = [
        ("output", _selector(output)),
        # Hyprland takes the mode without the Hz suffix the profile stores.
        ("mode", mode[:-2] if mode.endswith("Hz") else mode),
        ("position", f"{int(output.get('x', 0))}x{int(output.get('y', 0))}"),
        ("scale", output.get("scale", 1)),
    ]
    if output.get("transform"):
        fields.append(("transform", int(output["transform"])))
    if output.get("mirror_of"):
        source = next((o for o in outputs if o.get("key") == output["mirror_of"]), None)
        fields.append(("mirror", _selector(source) if source else output["mirror_of"]))
    fields.append(("vrr", int(output.get("vrr", 0))))
    for key, unset in OPTIONAL_FIELD_UNSET_VALUES.items():
        if output.get(key) not in (None, "", unset):
            fields.append((HYPRLAND_FIELD_NAMES.get(key, key), output[key]))
    return fields


def _workspace_rules(profile: Profile) -> list[dict]:
    outputs = {o["key"]: o for o in profile.get("outputs", []) if o.get("key")}
    return [
        {**rule, "monitor": _selector(outputs[rule["output_key"]])}
        for rule in workspaces.rules(profile)
        if rule["output_key"] in outputs
    ]


def to_lua(profile: Profile) -> str:
    blocks = []
    for output in profile.get("outputs", []):
        body = "\n".join(f"  {k} = {_lua_value(v)}," for k, v in _fields(output, profile["outputs"]))
        blocks.append("hl.monitor({\n%s\n})" % body)
    for rule in _workspace_rules(profile):
        fields = [("workspace", rule["workspace"]), ("monitor", rule["monitor"])]
        if rule["default"]:
            fields.append(("default", True))
        body = "\n".join(f"  {k} = {_lua_value(v)}," for k, v in fields)
        blocks.append("hl.workspace_rule({\n%s\n})" % body)
    return HEADER + "\n\n" + "\n".join(blocks) + "\n"


def to_conf(profile: Profile) -> str:
    blocks = []
    for output in profile.get("outputs", []):
        body = "\n".join(
            "  %s = %s" % (k, "true" if v is True else "false" if v is False else v)
            for k, v in _fields(output, profile["outputs"])
        )
        blocks.append("monitorv2 {\n%s\n}" % body)
    for rule in _workspace_rules(profile):
        line = f'workspace = {rule["workspace"]}, monitor:{rule["monitor"]}'
        if rule["default"]:
            line += ", default:true"
        blocks.append(line)
    return CONF_HEADER + "\n\n" + "\n".join(blocks) + "\n"


def write(text: str, path: str = TARGET) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as handle:
        handle.write(text)
    os.replace(tmp, path)


def apply(profile: Profile) -> None:
    text = to_lua(profile)
    with contextlib.suppress(FileNotFoundError), open(TARGET, encoding="utf-8") as handle:
        if handle.read() == text:
            return
    write(text)
    hypr.reload()


def release() -> None:
    with contextlib.suppress(FileNotFoundError):
        os.remove(TARGET)
    hypr.reload()
