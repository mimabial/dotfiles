#!/usr/bin/env python3
import colorsys
import json
import math
import re
import sys
from pathlib import Path

from _common import hex_to_rgb, linear_to_srgb, oklab_to_linear_rgb, rgb_to_oklab

TRANSLUCENT_ALPHA = 0.40
PORTED_LAYOUT_RGBA_OPACITY = 0.9
PORTED_LAYOUT_TRANSLUCENT_OPACITY = 0.5
PORTED_LAYOUT_SEED_SLOTS = (8, 4, 5)
PORTED_LAYOUT_ACCENT_LIGHTNESS = (0.24, 0.32, 0.39, 0.45, 0.52, 0.62, 0.75, 0.80, 0.90)
HLS_MID_LIGHTNESS = 0.5
TONE_LIGHTNESS_SCALE = 100
TONE_CHROMA_SCALE = 1000
GAMUT_BISECTION_STEPS = 24
GAMUT_EDGE_TOLERANCE = 1e-4
PLACEHOLDER_SPAN = re.compile(r'<span size="\$(ph\.(\d+)\.(\d+)\.[0-9a-f]+)">(.*)</span>')


def emit_rgb_components(palette: dict) -> None:
    print("# Autogenerated hyprlock colors (RGB 0-255)\n")
    for i, c in enumerate(palette["colors"]):
        r, g, b = hex_to_rgb(c)
        print(f"$c{i}.r = {r}")
        print(f"$c{i}.g = {g}")
        print(f"$c{i}.b = {b}")
        print(f"$color{i} = rgb({r}, {g}, {b})")
        print()
    for short, key, long in (("bg", "bg", "background"), ("fg", "fg", "foreground"), ("cx", "cursor", "cursor")):
        if key not in palette:
            continue
        r, g, b = hex_to_rgb(palette[key])
        print(f"${short}.r = {r}")
        print(f"${short}.g = {g}")
        print(f"${short}.b = {b}")
        print(f"${long} = rgb({r}, {g}, {b})")
        print()


def emit_translucent_variants(palette: dict) -> None:
    alpha = f"{round(255 * TRANSLUCENT_ALPHA):02X}"
    print(f"# Alpha ({TRANSLUCENT_ALPHA:.0%} = 0x{alpha})")
    for i, c in enumerate(palette["colors"]):
        r, g, b = hex_to_rgb(c)
        print(f"$color{i}_alpha = rgba({r:02x}{g:02x}{b:02x}{alpha})")
    print()
    for short, key in (("background", "bg"), ("foreground", "fg")):
        r, g, b = hex_to_rgb(palette[key])
        print(f"${short}_alpha = rgba({r:02x}{g:02x}{b:02x}{alpha})")
    print()


def emit_pango_hex(palette: dict) -> None:
    print("# Hex per slot, for Pango markup")
    for i, c in enumerate(palette["colors"]):
        print(f"$c{i}.hex = {c.lstrip('#').lower()}")
    for short in ("bg", "fg"):
        print(f"${short}.hex = {palette[short].lstrip('#').lower()}")
    print()


def emit_ported_color(name: str, rgb: tuple[int, int, int]) -> None:
    r, g, b = rgb
    print(f"${name} = {r:02X}{g:02X}{b:02X}")
    print(f"${name}_rgba = rgba({r},{g},{b},{PORTED_LAYOUT_RGBA_OPACITY})")


def emit_ported_layout_colors(palette: dict) -> None:
    accent_lightness = PORTED_LAYOUT_ACCENT_LIGHTNESS
    if palette.get("color_variant") == "light":
        accent_lightness = accent_lightness[::-1]
    seeds = (palette["bg"], *(palette["colors"][slot] for slot in PORTED_LAYOUT_SEED_SLOTS))
    for n, seed in enumerate(seeds, 1):
        seed_rgb = hex_to_rgb(seed)
        hue, lightness, saturation = colorsys.rgb_to_hls(*(v / 255 for v in seed_rgb))
        emit_ported_color(f"primary_{n}", seed_rgb)
        emit_ported_color(f"text_{n}", hex_to_rgb(palette["fg"] if lightness < HLS_MID_LIGHTNESS else palette["bg"]))
        for m, level in enumerate(accent_lightness, 1):
            emit_ported_color(f"p{n}_accent_{m}", tuple(round(v * 255) for v in colorsys.hls_to_rgb(hue, level, saturation)))
        r, g, b = seed_rgb
        print(f"$primary_{n + len(seeds)}_rgba = rgba({r},{g},{b},{PORTED_LAYOUT_TRANSLUCENT_OPACITY})")


# Tones layouts reference as $tone.cN.L.C: slot N's hue at OKLab lightness L/100 and
# chroma C/1000, never more colourful than the slot itself, clipped into sRGB.
def gamut_clipped_tone(slot_rgb: tuple[int, int, int], lightness: float, chroma: float) -> tuple[int, ...]:
    _, a, b = rgb_to_oklab(slot_rgb)
    angle, chroma = math.atan2(b, a), min(chroma, math.hypot(a, b))
    in_gamut = lambda c: all(
        -GAMUT_EDGE_TOLERANCE <= v <= 1 + GAMUT_EDGE_TOLERANCE
        for v in oklab_to_linear_rgb(lightness, c * math.cos(angle), c * math.sin(angle))
    )
    low, high = 0.0, chroma
    if not in_gamut(high):
        for _ in range(GAMUT_BISECTION_STEPS):
            mid = (low + high) / 2
            low, high = (mid, high) if in_gamut(mid) else (low, mid)
        chroma = low
    lin = oklab_to_linear_rgb(lightness, chroma * math.cos(angle), chroma * math.sin(angle))
    return tuple(round(255 * min(1, max(0, linear_to_srgb(v)))) for v in lin)


def emit_tones(palette: dict, tone_references: str) -> None:
    tones = tone_references.split()
    if tones:
        print("\n# Tones used by layouts")
    for name in tones:
        _, slot, lightness, chroma = name.lstrip("$").split(".")
        slot_rgb = hex_to_rgb(palette["colors"][int(slot[1:])])
        r, g, b = gamut_clipped_tone(slot_rgb, int(lightness) / TONE_LIGHTNESS_SCALE, int(chroma) / TONE_CHROMA_SCALE)
        print(f"{name}.r = {r}\n{name}.g = {g}\n{name}.b = {b}\n{name}.hex = {r:02x}{g:02x}{b:02x}")


def emit_placeholder_sizes(font_name: str, placeholder_markup: str) -> None:
    # Placeholders cannot run commands, so each <span size="$ph.WIDTH.PT.ID"> gets the
    # largest size, up to PT, at which its text fits WIDTH in the current font.
    placeholders = [m.groups() for m in PLACEHOLDER_SPAN.finditer(placeholder_markup)]
    if not placeholders:
        return
    import gi
    gi.require_version("Pango", "1.0")
    gi.require_version("PangoCairo", "1.0")
    import cairo
    from gi.repository import Pango, PangoCairo
    context = PangoCairo.create_context(cairo.Context(cairo.ImageSurface(cairo.FORMAT_ARGB32, 1, 1)))
    def width(markup, size):
        layout = Pango.Layout.new(context)
        layout.set_font_description(Pango.FontDescription.from_string(font_name or "Sans"))
        layout.set_markup(f'<span size="{size}">{markup}</span>', -1)
        return layout.get_pixel_size()[0]
    def largest_fitting_size(markup, room, largest):
        if width(markup, largest) <= room:
            return largest
        low, high = Pango.SCALE, largest
        while high - low > 1:
            middle = (low + high) // 2
            low, high = (middle, high) if width(markup, middle) <= room else (low, middle)
        return low
    print("\n# Placeholder sizes that fit their input field")
    for name, room, points, text in dict.fromkeys(placeholders):
        # Colours do not change width, and they may hold variables Pango cannot parse.
        plain = re.sub(r"<span\b[^>]*>", "<span>", text.replace("##", "#"))
        print(f"${name} = {largest_fitting_size(plain, int(room), int(points) * Pango.SCALE)}")


def render_hyprlock_colors(palette: dict, font_name: str, corner_radius: str, tone_references: str, placeholder_markup: str) -> None:
    emit_rgb_components(palette)
    emit_translucent_variants(palette)
    emit_pango_hex(palette)
    emit_ported_layout_colors(palette)
    emit_tones(palette, tone_references)
    emit_placeholder_sizes(font_name, placeholder_markup)
    if font_name:
        print(f"\n$font = {font_name}")
    print(f"$rounding = {corner_radius}")


def main():
    palette_file, font_name, corner_radius, tone_references, placeholder_markup = sys.argv[1:]
    render_hyprlock_colors(json.loads(Path(palette_file).read_text()), font_name, corner_radius, tone_references, placeholder_markup)


if __name__ == "__main__":
    main()
