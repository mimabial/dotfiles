#!/usr/bin/env python3
import hashlib
import json
import sys
from pathlib import Path

from _common import (LIGHT_LUMINANCE_THRESHOLD, RENDER_OUTPUT_DIR, atomic_write, cache_hit, cache_store, hex_to_rgb,
                     luminance, palette_path, short_digest)

PALETTE = palette_path()
OUT_FILE = RENDER_OUTPUT_DIR / "gimp" / "gimp.css"

APP = "gimp"

def css_rgb(c):
    r, g, b = hex_to_rgb(c)
    return f"rgb({r},{g},{b})"

def css_rgba(c, a):
    r, g, b = hex_to_rgb(c)
    return f"rgba({r},{g},{b},{a})"

def clamp_rgb_channel(v):
    return max(0, min(255, v))

def shift_rgb_channels_as_css(c, offset):
    r, g, b = (clamp_rgb_channel(x + offset) for x in hex_to_rgb(c))
    return f"rgb({r},{g},{b})"

def blend_rgb_colors_as_css(first_color, second_color, second_color_percent):
    r1, g1, b1 = hex_to_rgb(first_color)
    r2, g2, b2 = hex_to_rgb(second_color)
    r = (r1 * (100 - second_color_percent) + r2 * second_color_percent) // 100
    g = (g1 * (100 - second_color_percent) + g2 * second_color_percent) // 100
    b = (b1 * (100 - second_color_percent) + b2 * second_color_percent) // 100
    return f"rgb({clamp_rgb_channel(r)},{clamp_rgb_channel(g)},{clamp_rgb_channel(b)})"

def main():
    if not PALETTE.is_file():
        sys.exit(f"render/gimp: missing {PALETTE}")

    palette = json.loads(PALETTE.read_text())
    bg, fg = palette["bg"], palette["fg"]

    hasher = hashlib.sha256()
    hasher.update(PALETTE.read_bytes())
    hasher.update(Path(__file__).read_bytes())
    hasher.update(Path(__file__).with_name("_common.py").read_bytes())
    digest = short_digest(hasher)

    if cache_hit(APP, digest) and OUT_FILE.exists():
        return

    is_dark = luminance(bg) < LIGHT_LUMINANCE_THRESHOLD

    widget_bg        = shift_rgb_channels_as_css(bg, -18)
    extreme_bg       = shift_rgb_channels_as_css(bg, -24)
    selected         = shift_rgb_channels_as_css(bg, -30)
    extreme_selected = shift_rgb_channels_as_css(bg, -5)
    border           = shift_rgb_channels_as_css(bg, -34)
    strong_border    = shift_rgb_channels_as_css(bg, -20)
    stronger_border  = shift_rgb_channels_as_css(bg, 15)
    edge_border      = shift_rgb_channels_as_css(bg, -34)
    hover            = shift_rgb_channels_as_css(bg, 40 if is_dark else -40)
    dimmed_fg        = blend_rgb_colors_as_css(fg, bg, 40)
    disabled_fg      = blend_rgb_colors_as_css(fg, bg, 45)
    disabled_button  = blend_rgb_colors_as_css(fg, bg, 60)
    scrollbar_slider = blend_rgb_colors_as_css(fg, bg, 30)
    scrollbar_trough = css_rgb(bg)
    ruler            = css_rgba(bg, "0.3")
    fg_rgb           = css_rgb(fg)
    bg_rgb           = css_rgb(bg)

    css = f"""/* Auto-generated by render/gimp */

@define-color fg-color               {fg_rgb};
@define-color bg-color               {bg_rgb};
@define-color border-color           {border};
@define-color dimmed-fg-color        {dimmed_fg};
@define-color disabled-fg-color      {disabled_fg};
@define-color disabled-button-color  {disabled_button};
@define-color hover-color            {hover};
@define-color widget-bg-color        {widget_bg};
@define-color selected-color         {selected};
@define-color extreme-bg-color       {extreme_bg};
@define-color extreme-selected-color {extreme_selected};
@define-color strong-border-color    {strong_border};
@define-color stronger-border-color  {stronger_border};
@define-color edge-border-color      {edge_border};
@define-color scrollbar-slider-color {scrollbar_slider};
@define-color scrollbar-trough-color {scrollbar_trough};
@define-color ruler-color            {ruler};
"""

    atomic_write(OUT_FILE, css)

    cache_store(APP, digest)

if __name__ == "__main__":
    main()
