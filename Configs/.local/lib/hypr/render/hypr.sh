#!/usr/bin/env bash
set -euo pipefail
source "${BASH_SOURCE[0]%/*}/_render_job.bash"
declare -A render_job=()
# Pack hypr.theme is generation input, not runtime Hyprland configuration or a
# colors override. Always derive native Lua from it.
render_job_into render_job "${1:-}" hypr colors.meta hypr.theme

lua_output="${RENDER_CONFIG_DIR}/themes/colors.lua"
render_output_is_current render_job && [[ -f "${lua_output}" ]] && exit 0

render_stage_output_into render_job
trap 'rm -f -- "${render_job[staged_file]}"' EXIT

render_read_palette_into render_job

# Border source of truth:
#   theme mode     -> pack's hypr.theme verbatim (no border directives if the pack omits them)
#   wallpaper mode -> derived from palette
emit_hyprland_border_sections() {
  local -n border_job_ref="$1"
  if [[ "${border_job_ref[palette_mode]}" == "theme" && "${border_job_ref[palette_source]}" == theme:* ]]; then
    local pack_hypr="${border_job_ref[pack_override]}"
    [[ -f "${pack_hypr}" ]] || return 0
    awk '
      /^[[:space:]]*(general|group)[[:space:]]*\{/ { in_block=1; block_buf=""; matched=0; print; next }
      in_block && /^[[:space:]]*\}/ { if (matched) print block_buf; print; in_block=0; next }
      in_block {
        if ($0 ~ /^[[:space:]]*col\.(active_border|inactive_border|border_(active|inactive|locked_active|locked_inactive))[[:space:]]*=/) {
          block_buf = block_buf $0 "\n"; matched=1
        }
        next
      }
      { next }
    ' "${pack_hypr}"
  else
    local active_border_color="${border_job_ref[color4]#\#}ff"
    local inactive_border_background="${border_job_ref[color0]#\#}cc"
    local inactive_border_foreground="${border_job_ref[color8]#\#}cc"
    cat <<EOF
general {
    col.active_border = rgba(${active_border_color}) rgba(${active_border_color}) 45deg
    col.inactive_border = rgba(${inactive_border_background}) rgba(${inactive_border_foreground}) 45deg
}

group {
    col.border_active = rgba(${active_border_color}) rgba(${active_border_color}) 45deg
    col.border_inactive = rgba(${inactive_border_background}) rgba(${inactive_border_foreground}) 45deg
    col.border_locked_active = rgba(${active_border_color}) rgba(${active_border_color}) 45deg
    col.border_locked_inactive = rgba(${inactive_border_background}) rgba(${inactive_border_foreground}) 45deg
}
EOF
  fi
}

{
  printf '# Autogenerated by render/hypr.sh\n'
  printf '# Source: %s\n\n' "${render_job[palette_source]}"
  printf '# Standard theme colors\n'
  for ((i = 0; i < RENDER_ANSI_COLOR_COUNT; i++)); do
    printf '$color%s = %s\n' "$i" "${render_job[color$i]}"
  done
  printf '\n# Hyprland-friendly helpers (no leading '\''#'\'')\n'
  for ((i = 0; i < RENDER_ANSI_COLOR_COUNT; i++)); do
    printf '$color%see = %see\n' "$i" "${render_job[color$i]#\#}"
  done
  printf '\n$background = %s\n' "${render_job[background_color]}"
  printf '$foreground = %s\n' "${render_job[foreground_color]}"
  printf '$cursor = %s\n\n' "${render_job[cursor_color]}"
  emit_hyprland_border_sections render_job
} > "${render_job[staged_file]}"

mv -f -- "${render_job[staged_file]}" "${render_job[output_file]}"
"${HYPR_LIB_DIR:-$HOME/.local/lib/hypr}/util/hypr-to-lua.py" --input "${render_job[output_file]}" --output "${lua_output}"
render_store_input_digest render_job
trap - EXIT
