hyprlock_paths_into() {
  local -n paths_ref="$1"
  paths_ref[cache]="${HYPR_CACHE_HOME:-${XDG_CACHE_HOME}/hypr}"
  paths_ref[config]="${HYPR_CONFIG_HOME:-${XDG_CONFIG_HOME}/hypr}"
  paths_ref[data]="${HYPR_DATA_HOME:-${XDG_DATA_HOME}/hypr}"
  paths_ref[conf]="${paths_ref[config]}/hyprlock.conf"
  paths_ref[shared_conf]="${paths_ref[data]}/hyprlock.conf"
  paths_ref[colors_conf]="${paths_ref[config]}/hyprlock/colors.conf"
  paths_ref[landing]="${paths_ref[cache]}/landing"
  paths_ref[artwork_base]="${paths_ref[landing]}/mpris"
  paths_ref[palette]="${HYPR_STATE_HOME:-${XDG_STATE_HOME}/hypr}/active-palette.json"
  paths_ref[icon]="${XDG_DATA_HOME}/icons/Hypr-Icon/hypr.png"
  paths_ref[face_icon]="$HOME/.face.icon"
  paths_ref[artwork_lock]="${XDG_RUNTIME_DIR}/hypr/hyprlock-art.lock"
  paths_ref[wallpaper_cache]="${WALLPAPER_CACHE_DIR:-${paths_ref[cache]}/wallpaper}"
  paths_ref[wallpaper_current]="${WALLPAPER_CURRENT_DIR:-${paths_ref[wallpaper_cache]}/current}"
  paths_ref[wallpaper_video]="${WALLPAPER_VIDEO_DIR:-${paths_ref[wallpaper_current]}/thumbnails}"
  paths_ref[wallpaper]="${paths_ref[wallpaper_current]}/wall.set"
  paths_ref[user_layouts]="${paths_ref[config]}/hyprlock"
  paths_ref[shared_layouts]="${paths_ref[data]}/hyprlock"
  paths_ref[scope]="${XDG_SESSION_DESKTOP:-unknown}-lockscreen.scope"
}
